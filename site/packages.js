function rule(id, statement, source, relation, confidence, tests) {
  return { id, statement, source, relation, confidence, tests }
}

function sub(id, name, rhythm, pattern, drums) {
  return { id, name, rhythm, pattern: pattern || "", drums: drums !== false, rendered: Boolean(pattern) && drums !== false }
}

function defineGenre(spec) {
  const steps = spec.steps.map((step) => ({
    status: "ready",
    figure: step.figure || "",
    touch: step.touch || "",
    pattern: step.pattern || "",
    era: step.era || spec.era || "today",
    gain: step.gain ?? 0.3,
    pan: step.pan ?? 0,
    sound: step.sound,
    role: step.role,
    renders: step.renders,
  }))
  return {
    id: spec.id,
    version: PACKAGE_VERSION,
    category: "genre",
    name: spec.name,
    description: spec.description,
    status: "partial",
    subgenres: spec.subgenres,
    traditions: spec.traditions,
    tempo: spec.tempo,
    meter: spec.meter,
    rhythmVocabulary: spec.rhythmVocabulary,
    groove: spec.groove,
    scales: spec.scales,
    chords: spec.chords,
    progressions: spec.progressions,
    melody: spec.melody,
    bass: spec.bass,
    palette: spec.palette,
    vocals: spec.vocals,
    structures: spec.structures,
    hooks: spec.hooks,
    density: spec.density,
    mixing: spec.mixing,
    mastering: spec.mastering,
    compatibility: spec.compatibility,
    hybridWith: spec.hybridWith,
    sources: spec.sources,
    rules: spec.rules,
    tests: spec.tests,
    recipe: {
      status: "partial",
      keepsMelody: true,
      shape: spec.shape || "",
      steps,
      planned: spec.planned,
    },
  }
}

