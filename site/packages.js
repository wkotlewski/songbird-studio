function byId(id) {
  return GENRES.find((genre) => genre.id === id) || null
}

function readySteps(genreId, subId, blendId) {
  if (genreId === "hybrid") {
    const first = byId(subId)
    const second = byId(blendId)
    if (!first || !second || first.id === "hybrid" || second.id === "hybrid" || first.id === second.id) return []
    const harmony = readySteps(first.id, first.subgenres[0]?.id).filter((step) => step.sound !== "Drums")
    const drums = readySteps(second.id, second.subgenres[0]?.id).filter((step) => step.sound === "Drums")
    return [...harmony, ...drums]
  }
  const genre = byId(genreId)
  if (!genre) return []
  const subgenre = genre.subgenres.find((item) => item.id === subId) || genre.subgenres[0]
  return genre.recipe.steps.filter((step) => step.status === "ready").filter((step) => {
    if (step.sound === "Drums" && subgenre && subgenre.drums === false) return false
    return true
  }).map((step) => {
    if (step.sound === "Drums" && subgenre && subgenre.pattern) return { ...step, pattern: subgenre.pattern }
    return { ...step }
  })
}

function plan(genreId, subId, blendId) {
  const genre = byId(genreId)
  if (!genre) return { will: [], wont: [], status: "planned", note: "" }
  const steps = readySteps(genreId, subId, blendId)
  const subgenre = genre.subgenres.find((item) => item.id === subId) || genre.subgenres[0]
  const will = steps.map((step) => step.renders || step.sound)
  const wont = genre.id === "hybrid"
    ? ["Anything either package marks as planned."]
    : genre.recipe.planned
  return {
    will,
    wont,
    status: genre.status,
    note: subgenre ? subgenre.rhythm : "",
    shape: genre.recipe.shape || "",
  }
}

